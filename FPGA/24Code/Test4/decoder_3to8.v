// ======================================
// 3-8线译码器（74LS138功能兼容）
// 输出低电平有效
// ======================================
module decoder_3to8 (
    input wire G1,           // 使能输入1（高电平有效）
    input wire G2A,          // 使能输入2A（低电平有效）
    input wire G2B,          // 使能输入2B（低电平有效）
    input wire [2:0] A,      // 3位地址输入
    output reg [7:0] Y       // 8位译码输出（低电平有效）
);

    always @(*) begin
        if (G1 && ~G2A && ~G2B) begin   // 使能条件满足
            case(A)
                3'b000: Y = 8'b1111_1110;  // Y0 = 0
                3'b001: Y = 8'b1111_1101;  // Y1 = 0
                3'b010: Y = 8'b1111_1011;  // Y2 = 0
                3'b011: Y = 8'b1111_0111;  // Y3 = 0
                3'b100: Y = 8'b1110_1111;  // Y4 = 0
                3'b101: Y = 8'b1101_1111;  // Y5 = 0
                3'b110: Y = 8'b1011_1111;  // Y6 = 0
                3'b111: Y = 8'b0111_1111;  // Y7 = 0
                default: Y = 8'b1111_1111;
            endcase
        end
        else begin
            Y = 8'b1111_1111;   // 使能无效时，所有输出为高电平
        end
    end

endmodule