`timescale 1ns/1ps

module tb_elevator_controller;

    // ============================================================
    // 测试信号定义
    // ============================================================
    reg clk;                    // 系统时钟
    reg rst_n;                  // 复位信号，低电平有效
    reg tick;                   // 电梯动作节拍信号
    reg [9:0] req;              // 楼层请求信号

    wire [3:0] current_floor;   // 当前楼层输出
    wire [1:0] direction;       // 电梯运行方向输出
    wire door_open;             // 电梯门状态输出
    wire [3:0] state_out;       // 当前状态输出

    // ============================================================
    // 实例化被测试模块
    // ============================================================
    elevator_controller uut (
        .clk(clk),
        .rst_n(rst_n),
        .tick(tick),
        .req(req),
        .current_floor(current_floor),
        .direction(direction),
        .door_open(door_open),
        .state_out(state_out)
    );

    // ============================================================
    // 产生系统时钟信号
    // 时钟周期为20ns
    // ============================================================
    initial begin
        clk = 0;
        forever #10 clk = ~clk;
    end

    // ============================================================
    // 产生tick信号
    // tick用于模拟电梯动作节拍
    // 每出现一次tick，电梯移动一层或开门计时一次
    // ============================================================
    initial begin
        tick = 0;
        forever begin
            #90 tick = 1;
            #20 tick = 0;
        end
    end

    // ============================================================
    // 测试激励过程
    // ============================================================
    initial begin
        // 初始状态
        rst_n = 0;                  // 先复位
        req = 10'b0000000000;       // 初始无楼层请求

        #50;
        rst_n = 1;                  // 释放复位，电梯从1楼开始工作

        // ------------------------------------------------------------
        // 测试1：当前电梯在1楼，请求5楼
        // req[4] = 1 表示5楼有请求
        // 预期：电梯从1楼上行到5楼，到达后开门
        // ------------------------------------------------------------
        #60;
        req = 10'b0000010000;
        #40;
        req = 10'b0000000000;

        // ------------------------------------------------------------
        // 测试2：电梯运行过程中，同时请求3楼和8楼
        // req[2] = 1 表示3楼请求
        // req[7] = 1 表示8楼请求
        // 预期：电梯根据当前位置选择距离最近的楼层优先响应
        // ------------------------------------------------------------
        #300;
        req = 10'b0010000100;
        #40;
        req = 10'b0000000000;

        // ------------------------------------------------------------
        // 测试3：请求10楼
        // req[9] = 1 表示10楼请求
        // 预期：电梯上行到10楼，到达后开门
        // ------------------------------------------------------------
        #500;
        req = 10'b1000000000;
        #40;
        req = 10'b0000000000;

        // ------------------------------------------------------------
        // 测试4：请求2楼
        // req[1] = 1 表示2楼请求
        // 预期：电梯从当前楼层下行到2楼，到达后开门
        // ------------------------------------------------------------
        #700;
        req = 10'b0000000010;
        #40;
        req = 10'b0000000000;

        // ------------------------------------------------------------
        // 继续仿真一段时间，观察电梯是否回到空闲状态
        // ------------------------------------------------------------
        #1500;
        $stop;                      // 停止仿真
    end

endmodule