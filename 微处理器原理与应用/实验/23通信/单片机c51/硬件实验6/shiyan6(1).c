void Delayms(unsigned int xms)
{
    unsigned char i, j;
    while (xms--)
    {
        i = 2;
        j = 239;
        do
        {
            while (--j);
        } while (--i);
    }
}
void Delayus(unsigned int xms)
{
    unsigned char i, j;
    while (xms--)
    {
        i = 2;
        j = 24;
        do
        {
            while (--j);
        } while (--i);
    }
}
void Check_busy() 
{ 
	uchar a; 
	RW=1; 
	RS=0; 
	E=1;
	while(1) 
	{ 
		E=0;
		if(!(P1&0x80))
		break;
		E=1; 
		a++; 
		if(a>10)
		break; 
	} 
}
void write_cmd(unsigned char a) 
{ 
	Check_busy(); 
	RS=0; 
	RW=0; 
	E=0;
	P0=a; 
  Delayms(10);	
	E=1; 
  Delayms(10);
	E=0; 
} 
void write_data(unsigned char a) 
{ 
	Check_busy(); 
	RS=1; 
	RW=0;
	E=0;
	P0=a;
  Delayms(10);	
	E=1; 
  Delayms(10);	
	E=0; 
}
