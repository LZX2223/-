ORG 0000H                    ; 程序复位入口地址为 0000H
AJMP MAIN                    ; 单片机复位后跳转到 MAIN 主程序

ORG 0030H                    ; 主程序从程序存储器 0030H 地址开始存放

MAIN:
    MOV SP,#60H              ; 设置堆栈指针 SP 为 60H，避免堆栈与低地址 RAM 数据区冲突

    MOV A,#0H                ; 将累加器 A 清零，A = 00H
    MOV R1,#30H              ; 将 R1 设置为 30H，作为片内 RAM 的间接寻址指针
    MOV R7,#10H              ; 将 R7 设置为 10H，即十进制 16，作为循环次数计数器

LOOP1:
    MOV @R1,A                ; 将 A 中的内容写入 R1 指向的 RAM 单元中
                              ; 第一次写入 30H 单元，内容为 00H

    INC R1                   ; R1 加 1，指向下一个 RAM 单元
                              ; 例如从 30H 指向 31H

    DJNZ R7,LOOP1            ; R7 减 1，如果 R7 不为 0，则跳回 LOOP1 继续循环
                              ; 该循环共执行 16 次，将 30H~3FH 单元全部清零

    NOP                      ; 空操作，占用一个机器周期，不改变任何寄存器或存储器内容

    MOV R1,#30H              ; 重新将 R1 设置为 30H，从 RAM 30H 单元开始写入数据
    MOV R7,#10H              ; 重新将 R7 设置为 10H，即循环 16 次

LOOP:
    MOV @R1,A                ; 将 A 中的数据写入 R1 指向的 RAM 单元
                              ; 第一次写入 30H 单元

    INC R1                   ; R1 加 1，指向下一个 RAM 地址

    INC A                    ; A 加 1，使下一次写入的数据递增

    DJNZ R7,LOOP             ; R7 减 1，如果 R7 不为 0，则继续循环
                              ; 该循环共执行 16 次

    SJMP $                   ; 程序停在当前位置，形成死循环，防止程序继续向下执行

END                           ; 汇编程序结束