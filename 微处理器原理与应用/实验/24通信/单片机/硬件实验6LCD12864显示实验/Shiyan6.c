sbit RST=P2^0;
sbit E=P2^2;
sbit RW=P2^3;
sbit RS=P2^4;
sbit CS1=P2^5;
sbit CS2=P2^6;


void Delayms(unsigned int xms)
{
    unsigned char i, j;
    while (xms--)
    {
        i = 2;
        j = 239;
        do
        {
            while (--j);
        } while (--i);
    }
}
void Delayus(unsigned int xms)
{
    unsigned char i, j;
    while (xms--)
    {
        i = 2;
        j = 24;
        do
        {
            while (--j);
        } while (--i);
    }
}
void Check_busy()
{
    Delayus(20);
}

void write_cmd(uchar cmd)
{
    RS=0;
    RW=0;

    P0=cmd;

    E=1;
    _nop_();
    _nop_();
    E=0;

    Delayus(20);
}

void write_data(uchar dat)
{
    RS=1;
    RW=0;

    P0=dat;

    E=1;
    _nop_();
    _nop_();
    E=0;

    Delayus(20);
}

void LCD_Init()
{
    RST=1;

    CS1=1;
    CS2=1;

    write_cmd(0x3F);
    write_cmd(0xC0);
    write_cmd(0xB8);
    write_cmd(0x40);

    Delayms(20);
}

void set_xy(uchar page,uchar col)
{
    if(col<64)
    {
        CS1=0;
        CS2=1;
    }
    else
    {
        CS1=1;
        CS2=0;
        col-=64;
    }

    write_cmd(0xB8+page);
    write_cmd(0x40+col);
}

void Disp_hz(uchar page,uchar col,uchar *p)
{
    uchar i;

    for(i=0;i<16;i++)
    {
        set_xy(page,col+i);
        write_data(p[i]);
    }

    for(i=0;i<16;i++)
    {
        set_xy(page+1,col+i);
        write_data(p[i+16]);
    }
}

