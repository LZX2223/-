

clear; clc; close all;  % 清空工作区所有变量、清除命令窗口内容
% 分子系数 B（对应H(z)的分子多项式，从z^0项到z^{-5}项）
B = [0.0528, 0.0797, 0.1295, 0.1295, 0.0797, 0.0528]; 
% 分母系数 A（对应H(z)的分母多项式，从z^0=1项到z^{-5}项）
A = [1, -1.8107, 2.4947, -1.8801, 0.9537, -0.2336];   

% 计算系统的零点、极点和增益
% 使用函数 tf2zp 将分子分母系数转换为零极点增益形式
[z, p, k] = tf2zp(B, A);  % 返回值：z为所有零点，p为所有极点，k为系统增益常数K
% 实验要求需要知道具体的零、极点数值，因此必须用disp输出
disp('系统零点');  % 显示标题
disp(z);                           % 打印所有零点数值（复数形式）

disp('系统极点');  % 显示标题
disp(p);                           % 打印所有极点数值（复数形式）

disp('系统增益'); % 显示标题
disp(k);                           % 打印增益常数K

% 绘制零、极点分布图
% 使用zplane函数直接绘制零极点分布图
% zplane(B, A) 会自动在单位圆上画出零点（o）和极点（x），并标出单位圆
figure('Name', '零、极点分布图', 'NumberTitle', 'off');  % 创建一个带标题的图形窗口
zplane(B, A);                    % 直接传入系数绘制零极点图
title('系统 H(z) 的零、极点分布图');  % 设置图形标题
xlabel('实部 (Real Part)');      % x轴标签
ylabel('虚部 (Imaginary Part)'); % y轴标签
grid on;                         % 打开网格线，便于观察零极点位置

% 计算系统的频率响应
% 设置频率采样点数N=1024
N = 1024;                        % 频率采样点数

% 使用freqz函数计算频率响应
% 返回值H是H(e^{jω})在各频率点的复数值，w是0到π的归一化角频率
[H, w] = freqz(B, A, N);         % 计算离散时间系统的频率响应

% 绘制幅度频率响应曲线
% 将幅度转换为dB单位（20*log10(|H|)），这是信号处理中最标准、最清晰的显示方式
mag_db = 20 * log10(abs(H));     % 计算幅度响应的分贝值（dB）

% 创建图形窗口并绘制曲线
figure('Name', '幅度频率响应曲线', 'NumberTitle', 'off');  % 创建带标题的图形窗口
plot(w/pi, mag_db, 'LineWidth', 1.5);  % x轴归一化为0~1（w/π）
title('系统 H(z) 的幅度频率响应曲线');  % 设置图形标题
xlabel('归一化频率 (\times \pi rad/sample)');  % x轴标签
ylabel('幅度 (dB)');             % y轴标签，单位dB
grid on;                         % 打开网格线
axis([0 1 -60 10]);              % 设置坐标轴范围（x:0~1，y:-60~10 dB）

