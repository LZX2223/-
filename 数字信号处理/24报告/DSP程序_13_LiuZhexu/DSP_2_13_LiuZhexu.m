%% 【实验内容】 编制程序求解两个离散系统的单位抽样响应和阶跃响应，并绘制图形

% 清空工作区、命令行和图形窗口
clear; clc; close all;

%% ====================== 系统1：差分方程形式 ======================
% 系统1的差分方程：
% y[n] + 0.75 y[n-1] + 0.125 y[n-2] = x[n] - x[n-1]

% 定义系统1的系数
a1 = [1, 0.75, 0.125];      % 输出y的系数（即系统函数的分母系数）
b1 = [1, -1, 0, 0];         % 输入x的系数（即系统函数的分子系数），后面补0

% 设置仿真长度
N = 10;                     % 取10个样本点

% 生成单位抽样信号 δ[n]（单位脉冲响应输入）
delta = zeros(1, N);        % 创建全零向量
delta(1) = 1;               % n=0时刻为1，即单位抽样序列

% 生成单位阶跃信号 u[n]
step = ones(1, N);          % 从n=0开始全为1的阶跃序列

% 计算系统1的单位抽样响应 
h1 = filter(b1, a1, delta); % 使用filter函数求解线性常系数差分方程的输出

% 计算系统1的单位阶跃响应 
s1 = filter(b1, a1, step);

%% ====================== 系统2：直接卷积形式（FIR系统） ======================
% 系统2的差分方程：
% y[n] = 0.25 * (x[n-1] + x[n-2] + x[n-3] + x[n-4])

% 系统2是FIR滤波器，其冲激响应本身就是系数
b2 = [0, 0.25, 0.25, 0.25, 0.25];   % 对应x[n-1]到x[n-4]的系数，前补0（n=0处系数为0）
a2 = 1;                             % FIR系统，分母系数为1

% 计算系统2的单位抽样响应 
h2 = filter(b2, a2, delta);

% 计算系统2的单位阶跃响应
s2 = filter(b2, a2, step);

%% ====================== 绘制图形 ======================

% 创建图形窗口
figure('Name', '两个离散系统的单位抽样响应和阶跃响应', 'NumberTitle', 'off', 'Position', [100 100 1200 800]);

% 子图1：系统1 单位抽样响应
subplot(2,2,1);
stem(0:N-1, h1, 'b', 'filled', 'LineWidth', 1.2);
title('系统1 - 单位抽样响应');
xlabel('n'); ylabel('幅度');
grid on;

% 子图2：系统1 单位阶跃响应
subplot(2,2,2);
stem(0:N-1, s1, 'r', 'filled', 'LineWidth', 1.2);
title('系统1 - 单位阶跃响应 ');
xlabel('n'); ylabel('幅度');
grid on;

% 子图3：系统2 单位抽样响应
subplot(2,2,3);
stem(0:N-1, h2, 'b', 'filled', 'LineWidth', 1.2);
title('系统2 - 单位抽样响应 ');
xlabel('n'); ylabel('幅度');
grid on;

% 子图4：系统2 单位阶跃响应
subplot(2,2,4);
stem(0:N-1, s2, 'r', 'filled', 'LineWidth', 1.2);
title('系统2 - 单位阶跃响应 ');
xlabel('n'); ylabel('幅度');
grid on;

% 添加整体标题
sgtitle('两个离散系统的单位抽样响应和阶跃响应');

